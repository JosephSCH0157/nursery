-- existed in production before migration ownership was established. Create its
-- complete production-equivalent contract before handle_new_user depends on it.
create table public.profiles (
  id bigint generated by default as identity (
    sequence name public.profiles_id_seq
    start with 1 increment by 1 no minvalue no maxvalue cache 1
  ) not null,
  created_at timestamptz not null default now(),
  user_id uuid not null default auth.uid(),
  display_name text,
  tier text not null default '"free"'::text,
  settings jsonb not null default '{}'::jsonb,
  settings_rev bigint not null default 0,
  settings_updated_at timestamptz not null default now(),
  asr_settings jsonb not null default '{}'::jsonb,
  asr_calibration_profiles jsonb not null default '[]'::jsonb,
  asr_updated_at timestamptz not null default now(),
  is_legacy boolean not null default false,
  anvil_paid boolean not null default false,
  stripe_customer_id text,
  stripe_subscription_id text,
  subscription_status text,
  current_period_end timestamptz,
  email text,
  avatar_url text,
  updated_at timestamptz,
  constraint profiles_pkey primary key (id),
  constraint profiles_user_id_key unique (user_id),
  constraint profiles_user_id_fkey foreign key (user_id)
    references auth.users(id) on delete cascade
);

alter table public.profiles owner to postgres;
alter sequence public.profiles_id_seq owner to postgres;

create index profiles_settings_gin on public.profiles using gin (settings);
create index profiles_stripe_customer_id_idx on public.profiles (stripe_customer_id);
create index profiles_stripe_subscription_id_idx on public.profiles (stripe_subscription_id);
create unique index profiles_user_id_uniq on public.profiles (user_id);

alter table public.profiles enable row level security;

create policy profiles_insert_own
on public.profiles for insert to authenticated
with check (auth.uid() = user_id);

create policy profiles_select_own
on public.profiles for select to authenticated
using (auth.uid() = user_id);

create policy profiles_update_own
on public.profiles for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

grant all on table public.profiles to anon;
grant all on table public.profiles to authenticated;
