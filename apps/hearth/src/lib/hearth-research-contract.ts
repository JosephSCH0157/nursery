export type HearthResearchResult = {
  mode: HearthResearchMode;
  runtimeStatus: HearthResearchRuntimeStatus;
  providerStatus?: HearthResearchProviderStatus;
  brief?: HearthResearchBrief;
  evidence?: HearthResearchEvidence[];
  artifact?: HearthResearchArtifact | null;
  sources: HearthResearchSource[];
  synthesis: HearthResearchSynthesis;
};

export const HEARTH_RESEARCH_DEFAULT_MAX_SOURCES = 6;

function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === "object" && !Array.isArray(value);
}

function stringArray(value: unknown, limit = 24): string[] {
  return Array.isArray(value)
    ? value.filter((entry): entry is string => typeof entry === "string").map((entry) => entry.trim()).filter(Boolean).slice(0, limit)
    : [];
}

function normalizeAuthority(value: unknown): HearthResearchSourceAuthority {
  return value === "primary_government"
    || value === "primary_institutional"
    || value === "scholarly_technical"
    || value === "reputable_secondary"
    || value === "general_reference"
    || value === "promotional_general"
    || value === "unassessed"
    ? value
    : "unassessed";
}

function normalizeAccessFailure(value: unknown): HearthResearchAccessFailureReason | null {
  return value === "authentication_required"
    || value === "paywall"
    || value === "access_denied"
    || value === "timeout"
    || value === "unsupported_content"
    || value === "http_error"
    || value === "extraction_failed"
    || value === "cancelled"
    ? value
    : null;
}

export function normalizeHearthResearchBrief(value: unknown): HearthResearchBrief | null {
  if (!isRecord(value) || value.schema !== "forge.hearth.research-brief.v1") return null;
  const workpieceId = typeof value.workpieceId === "string" ? value.workpieceId.trim() : "";
  const briefFingerprint = typeof value.briefFingerprint === "string" ? value.briefFingerprint.trim() : "";
  const creatorRequest = typeof value.creatorRequest === "string" ? value.creatorRequest.trim() : "";
  if (!workpieceId || !briefFingerprint || !creatorRequest) return null;
  return {
    schema: "forge.hearth.research-brief.v1",
    workspaceId: typeof value.workspaceId === "string" ? value.workspaceId : null,
    workpieceId,
    briefFingerprint,
    creatorRequest,
    episodeTitle: typeof value.episodeTitle === "string" ? value.episodeTitle : "",
    goals: stringArray(value.goals, 8),
    queries: stringArray(value.queries, 8),
    sourcePriorities: stringArray(value.sourcePriorities, 8),
  };
}

export function normalizeHearthResearchArtifact(value: unknown): HearthResearchArtifact | null {
  if (!isRecord(value)) return null;
  const briefFingerprint = typeof value.briefFingerprint === "string" ? value.briefFingerprint.trim() : "";
  const workpieceId = typeof value.workpieceId === "string" ? value.workpieceId.trim() : "";
  const status = value.status;
  if (!briefFingerprint || !workpieceId || (status !== "complete" && status !== "partial" && status !== "failed")) return null;
  const findings = Array.isArray(value.findings) ? value.findings.flatMap((entry) => {
    if (!isRecord(entry)) return [];
    const text = typeof entry.text === "string" ? entry.text.trim() : "";
    const findingStatus = entry.status;
    if (!text || (findingStatus !== "verified_fact" && findingStatus !== "reported_claim" && findingStatus !== "uncertain" && findingStatus !== "editorial_interpretation")) return [];
    return [{
      text,
      status: findingStatus,
      sourceIds: stringArray(entry.sourceIds, 12),
      scope: entry.scope === "adjacent_context" ? "adjacent_context" : "current_subject",
    } satisfies HearthResearchFinding];
  }).slice(0, 24) : [];
  return {
    briefFingerprint,
    workpieceId,
    status,
    findings,
    uncertainties: stringArray(value.uncertainties, 16),
    editorialInterpretation: stringArray(value.editorialInterpretation, 16),
  };
}

export function buildHearthResearchRequest(input: {
  query: string;
  intent?: HearthResearchIntent | null;
  recencyPreference?: HearthResearchRequest["recencyPreference"] | null;
  maxSources?: number | null;
  requireDates?: boolean | null;
  requireFullExtraction?: boolean | null;
}): HearthResearchRequest {
  const rawQuery = input.query.trim();
  const boundedSourceCount = Number.isFinite(input.maxSources)
    ? Math.max(1, Math.min(12, Math.floor(input.maxSources as number)))
    : HEARTH_RESEARCH_DEFAULT_MAX_SOURCES;
  return {
    query: rawQuery,
    intent: input.intent ?? inferHearthResearchIntent(rawQuery),
    recencyPreference: input.recencyPreference ?? inferHearthResearchRecency(rawQuery),
    maxSources: boundedSourceCount,
    requireDates: input.requireDates ?? /\b(today|latest|recent|this week|this month|timeline|when)\b/i.test(rawQuery),
    requireFullExtraction: input.requireFullExtraction ?? false,
  };
}

export function buildEmptyHearthResearchResult(input: {
  mode: HearthResearchMode;
  runtimeStatus: HearthResearchRuntimeStatus;
  providerStatus?: HearthResearchProviderStatus;
  summary: string;
}): HearthResearchResult {
  return {
    mode: input.mode,
    runtimeStatus: input.runtimeStatus,
    ...(input.providerStatus ? { providerStatus: input.providerStatus } : {}),
    sources: [],
    synthesis: {
      summary: input.summary,
      keyPoints: [],
      uncertainties: [],
      coverageNote: "No sources were extracted in this pass.",
    },
  };
}

function inferHearthResearchIntent(query: string): HearthResearchIntent {
  const normalized = query.toLowerCase();
  if (/\bexample|examples|case study|incident|reporting\b/.test(normalized)) return "examples";
  if (/\bnews|latest|today|breaking\b/.test(normalized)) return "news";
  if (/\bbackground|history|explainer|what is|why\b/.test(normalized)) return "background";
  return "mixed";
}

function inferHearthResearchRecency(query: string): HearthResearchRequest["recencyPreference"] {
  const normalized = query.toLowerCase();
  if (/\btoday|this week|this month|latest|breaking\b/.test(normalized)) return "strict_recent";
  if (/\brecent|new|current\b/.test(normalized)) return "recent";
  return "none";
}

export function normalizeHearthResearchResult(value: unknown): HearthResearchResult | null {
  if (!isRecord(value)) return null;
  const mode = value.mode;
  const runtimeStatus = value.runtimeStatus;
  const providerStatus = value.providerStatus;
  const sources = Array.isArray(value.sources) ? value.sources : [];
  const synthesis = isRecord(value.synthesis) ? value.synthesis : null;
  if (
    mode !== "knowledge_first"
    && mode !== "retrieval_first"
    && mode !== "partial_retrieval"
  ) {
    return null;
  }
  if (
    runtimeStatus !== "ok"
    && runtimeStatus !== "partial"
    && runtimeStatus !== "no_results"
    && runtimeStatus !== "error"
  ) {
    return null;
  }
  if (
    providerStatus != null
    && providerStatus !== "configured_and_operational"
    && providerStatus !== "configured_but_provider_failing"
    && providerStatus !== "not_configured"
    && providerStatus !== "request_cancelled"
    && providerStatus !== "provider_rate_limited"
  ) {
    return null;
  }
  const normalizedSources: HearthResearchSource[] = [];
  for (const item of sources) {
    if (!isRecord(item)) continue;
    const extractionStatus = item.extractionStatus;
    if (
      extractionStatus !== "pending"
      && extractionStatus !== "extracted"
      && extractionStatus !== "partial"
      && extractionStatus !== "failed"
      && extractionStatus !== "skipped"
    ) {
      continue;
    }
    const sourceId = typeof item.sourceId === "string" ? item.sourceId.trim() : "";
    const url = typeof item.url === "string" ? item.url.trim() : "";
    if (!sourceId || !url) continue;

    const sourceTypeRaw = typeof item.sourceType === "string" ? item.sourceType.trim() : "";
    const sourceType: HearthResearchSourceType | null = (
      sourceTypeRaw === "web_page"
      || sourceTypeRaw === "web_article"
      || sourceTypeRaw === "youtube_video"
      || sourceTypeRaw === "tweet"
      || sourceTypeRaw === "unknown"
    ) ? sourceTypeRaw : null;

    const ingestModeRaw = typeof item.ingestMode === "string" ? item.ingestMode.trim() : "";
    const ingestMode: HearthResearchIngestMode | null = (
      ingestModeRaw === "metadata_only"
      || ingestModeRaw === "metadata_plus_transcript"
      || ingestModeRaw === "partial_failure"
    ) ? ingestModeRaw : null;

    const warningsRaw = Array.isArray(item.warnings) ? item.warnings : null;
    const warnings = warningsRaw
      ? warningsRaw
        .filter((entry): entry is string => typeof entry === "string")
        .map((entry) => entry.trim())
        .filter((entry) => entry.length > 0)
        .slice(0, 10)
      : null;

    const transcriptAvailable = typeof item.transcriptAvailable === "boolean" ? item.transcriptAvailable : null;

    const transcriptSegmentsRaw = Array.isArray(item.transcriptSegments) ? item.transcriptSegments : null;
    const transcriptSegments: HearthTranscriptSegment[] | null = transcriptSegmentsRaw
      ? transcriptSegmentsRaw
        .map((segment) => {
          if (!isRecord(segment)) return null;
          const cueIndex = typeof segment.cueIndex === "number" ? Math.floor(segment.cueIndex) : NaN;
          const startMs = typeof segment.startMs === "number" ? Math.floor(segment.startMs) : NaN;
          const endMs = typeof segment.endMs === "number" ? Math.floor(segment.endMs) : null;
          const text = typeof segment.text === "string" ? segment.text.trim() : "";
          if (!Number.isFinite(cueIndex) || cueIndex < 0) return null;
          if (!Number.isFinite(startMs) || startMs < 0) return null;
          if (endMs != null && (!Number.isFinite(endMs) || endMs < 0)) return null;
          if (!text) return null;
          return { cueIndex, startMs, endMs, text };
        })
        .filter((segment): segment is HearthTranscriptSegment => Boolean(segment))
        .slice(0, 600)
      : null;

    const transcriptMetaRaw = isRecord(item.transcriptMeta) ? item.transcriptMeta : null;
    const transcriptMetaSource = transcriptMetaRaw && typeof transcriptMetaRaw.source === "string"
      ? transcriptMetaRaw.source.trim()
      : "";
    const transcriptMeta: HearthTranscriptMeta | null = transcriptMetaRaw
      && (
        transcriptMetaSource === "youtube_timedtext"
        || transcriptMetaSource === "none"
        || transcriptMetaSource === "unknown"
      )
      ? {
        language: typeof transcriptMetaRaw.language === "string" ? transcriptMetaRaw.language : null,
        isAutoGenerated: typeof transcriptMetaRaw.isAutoGenerated === "boolean" ? transcriptMetaRaw.isAutoGenerated : null,
        source: transcriptMetaSource as HearthTranscriptMeta["source"],
      }
      : null;

    const quotesRaw = Array.isArray(item.attributedQuotes) ? item.attributedQuotes : null;
    const quotes: HearthAttributedQuote[] | null = quotesRaw
      ? quotesRaw
        .map((quote) => {
          if (!isRecord(quote)) return null;
          const text = typeof quote.text === "string" ? quote.text.trim() : "";
          if (!text) return null;
          const confidenceRaw = typeof quote.confidence === "string" ? quote.confidence.trim() : "";
          const confidence = (
            confidenceRaw === "direct"
            || confidenceRaw === "likely_direct"
            || confidenceRaw === "uncertain"
          ) ? confidenceRaw as HearthAttributedQuote["confidence"] : "uncertain";
          return {
            text,
            speaker: typeof quote.speaker === "string" ? quote.speaker : null,
            organization: typeof quote.organization === "string" ? quote.organization : null,
            context: typeof quote.context === "string" ? quote.context : null,
            confidence,
          };
        })
        .filter((quote): quote is HearthAttributedQuote => Boolean(quote))
        .slice(0, 12)
      : null;
    normalizedSources.push({
      sourceId,
      ...(sourceType ? { sourceType } : {}),
      ...(ingestMode ? { ingestMode } : {}),
      title: typeof item.title === "string" ? item.title : null,
      publisher: typeof item.publisher === "string" ? item.publisher : null,
      author: typeof item.author === "string" ? item.author : null,
      url,
      originalUrl: typeof item.originalUrl === "string" ? item.originalUrl : null,
      resolvedUrl: typeof item.resolvedUrl === "string" ? item.resolvedUrl : null,
      canonicalUrl: typeof item.canonicalUrl === "string" ? item.canonicalUrl : null,
      domain: typeof item.domain === "string" ? item.domain : null,
      publishedAt: typeof item.publishedAt === "string" ? item.publishedAt : null,
      updatedAt: typeof item.updatedAt === "string" ? item.updatedAt : null,
      retrievedAt: typeof item.retrievedAt === "string" ? item.retrievedAt : null,
      warnings,
      transcriptAvailable,
      snippet: typeof item.snippet === "string" ? item.snippet : null,
      extractedText: typeof item.extractedText === "string" ? item.extractedText : null,
      transcript: typeof item.transcript === "string" ? item.transcript : null,
      transcriptSegments,
      transcriptMeta,
      attributedQuotes: quotes,
      extractionStatus,
      extractionError: typeof item.extractionError === "string" ? item.extractionError : null,
      provenance: isRecord(item.provenance) && typeof item.provenance.briefFingerprint === "string"
        ? {
            origin: item.provenance.origin === "creator_url" || item.provenance.origin === "saved_episode_source" ? item.provenance.origin : "search",
            briefFingerprint: item.provenance.briefFingerprint,
            inspectedAt: typeof item.provenance.inspectedAt === "string" ? item.provenance.inspectedAt : null,
            inspectionStatus: item.provenance.inspectionStatus === "inspected" || item.provenance.inspectionStatus === "metadata_only" ? item.provenance.inspectionStatus : "inaccessible",
            accessFailureReason: normalizeAccessFailure(item.provenance.accessFailureReason),
            verifiedInCurrentRequest: item.provenance.verifiedInCurrentRequest === true,
          }
        : null,
    });
  }
  const normalizedSynthesis: HearthResearchSynthesis = {
    summary: synthesis && typeof synthesis.summary === "string" ? synthesis.summary : "",
    keyPoints: synthesis && Array.isArray(synthesis.keyPoints)
      ? synthesis.keyPoints.filter((entry): entry is string => typeof entry === "string")
      : [],
    uncertainties: synthesis && Array.isArray(synthesis.uncertainties)
      ? synthesis.uncertainties.filter((entry): entry is string => typeof entry === "string")
      : [],
    coverageNote: synthesis && typeof synthesis.coverageNote === "string" ? synthesis.coverageNote : "",
    refinementQueries: synthesis ? stringArray(synthesis.refinementQueries, 8) : [],
    unresolvedGoals: synthesis ? stringArray(synthesis.unresolvedGoals, 8) : [],
  };
  const brief = normalizeHearthResearchBrief(value.brief);
  const normalizedArtifact = normalizeHearthResearchArtifact(value.artifact);
  const normalizedEvidence: HearthResearchEvidence[] = Array.isArray(value.evidence) ? value.evidence.flatMap((entry) => {
    if (!isRecord(entry)) return [];
    const evidenceId = typeof entry.evidenceId === "string" ? entry.evidenceId.trim() : "";
    const briefFingerprint = typeof entry.briefFingerprint === "string" ? entry.briefFingerprint.trim() : "";
    const workpieceId = typeof entry.workpieceId === "string" ? entry.workpieceId.trim() : "";
    const sourceId = typeof entry.sourceId === "string" ? entry.sourceId.trim() : "";
    if (!evidenceId || !briefFingerprint || !workpieceId || !sourceId) return [];
    return [{
      evidenceId,
      briefFingerprint,
      workpieceId,
      sourceId,
      excerpt: typeof entry.excerpt === "string" ? entry.excerpt : null,
      authority: normalizeAuthority(entry.authority),
      state: entry.state === "inspected" ? "inspected" : "inaccessible",
      uncertainty: typeof entry.uncertainty === "string" ? entry.uncertainty : null,
    } satisfies HearthResearchEvidence];
  }).slice(0, 48) : [];
  const evidence = brief
    ? normalizedEvidence.filter((entry) => (
      entry.briefFingerprint === brief.briefFingerprint
      && entry.workpieceId === brief.workpieceId
    ))
    : [];
  const artifact = brief
    && normalizedArtifact?.briefFingerprint === brief.briefFingerprint
    && normalizedArtifact.workpieceId === brief.workpieceId
    ? normalizedArtifact
    : null;
  return {
    mode,
    runtimeStatus,
    ...(providerStatus ? { providerStatus } : {}),
    ...(brief ? { brief } : {}),
    ...(evidence.length ? { evidence } : {}),
    ...(artifact ? { artifact } : {}),
    sources: normalizedSources,
    synthesis: normalizedSynthesis,
  };
}
